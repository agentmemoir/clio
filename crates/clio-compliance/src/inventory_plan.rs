//! # Responsibility
//!
//! This module is responsible for the fixed row table of the compliance scope
//! ledger: one planned row per family and auxiliary record the ledger always
//! reports.
//!
//! ## Owns
//! - The fixed `ROW_PLAN` table and its report order
//!
//! ## Does not own
//! - The `RowPlan` schema and plan-to-store matching (`inventory_rows`)
//! - Deciding whether a row is open (`scope_inventory` in the parent module)
//!
//! ## Boundary
//!
//! Changes to which families the ledger reports, or to what is known about a
//! family, should normally require changes here. Changes to the row schema or
//! to how the plan is matched against a live store should not.
//!
//! Keep this module focused on the fixed row table.

