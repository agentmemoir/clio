//! # Responsibility
//!
//! This module is responsible for generating the Compose `.env` file in the
//! compose root and for the `clio compose` selection marker file.
//!
//! ## Owns
//! - The generated `.env` content (Compose variables only: no API keys), created
//!   directly with owner-only permissions
//! - The never-overwrite rule for an existing user-owned `.env`, and reading a
//!   value an existing `.env` sets
//! - The selection marker file recording the stack started by `up` (read by
//!   `down` so it tears down the same services)
//!
//! ## Does not own
//! - Asset materialization (see `compose_assets`)
//! - Effective-config resolution beyond reading the embed model value
//! - Docker argument construction (see `compose_docker`)
//!
//! ## Boundary
//!
//! Changes to which variables the generated `.env` holds should normally
//! require changes here. Changes to the materialized compose files should not
//! require changes here.
//!
//! Keep this module focused on the generated Compose environment file.

use crate::compose_assets;
use std::path::Path;

/// The generated `.env`. Populated from the effective config where applicable
/// (the embed model); deliberately holds NO online-service API keys. The
/// managed database has no password, so there is no database credential to keep
/// out of it. The user, database name, and port stay here because the
/// healthcheck and the Makefile read them, and they are not secret.
///
/// Every name below carries the `CLIO_` prefix, because that is the spelling
/// `compose.yml` substitutes on the host side. Nothing here is an unprefixed
/// name: one compose does not read would leave the container on its own default
/// while the file still looked correct.
pub(crate) fn env_contents(embed_model: &str) -> String {
    let gguf = compose_assets::GGUF_FILE_NAME;
    format!(
        "# Generated by `clio compose up` — consumed by compose.yml. Do not commit.\
         \n# Compose variables only; online-service API keys are deliberately not written here.\
         \n# The managed Postgres has no password: compose.yml publishes it on 127.0.0.1 and\
         \n# asks the image for trust authentication.\
         \nCLIO_POSTGRES_USER=clio\
         \nCLIO_POSTGRES_DB=clio\
         \nCLIO_POSTGRES_PORT=34310\
         \nCLIO_PG_SHARED_BUFFERS=128MB\
         \nCLIO_PG_WORK_MEM=4MB\
         \nCLIO_PG_MAX_CONNECTIONS=50\
         \nCLIO_EMBED_PORT=34311\
         \nCLIO_RERANK_PORT=34312\
         \nCLIO_EMBED_MODEL={embed_model}\
         \nCLIO_RERANK_MODEL=onnx-community/gte-multilingual-reranker-base\
         \nCLIO_EXTRACT_PORT=34313\
         \nCLIO_EXTRACT_GGUF={gguf}\
         \nCLIO_EXTRACT_CTX=2048\
         \nCLIO_EXTRACT_PARALLEL=1\
         \nCLIO_EXTRACT_THREADS=2\
         \n"
    )
}

/// Write `.env` into `root` with owner-only permissions (0600 on Unix). An
/// existing `.env` is user-owned configuration and is never overwritten;
/// nothing in it is echoed to stdout.
pub(crate) fn write_env(root: &Path, contents: &str) -> Result<(), String> {
    let path = root.join(".env");
    if path.exists() {
        eprintln!("using existing .env (not overwritten)");
        return Ok(());
    }
    create_env_file(&path, contents).map_err(|e| format!("cannot write .env: {e}"))
}

/// Create `.env` with owner-only permissions from the first byte: on Unix the
/// file is created with mode 0600 in one `open` call, so there is no window
/// where other users could read it before a later `chmod`. `create_new` also
/// refuses to clobber a file that appears between the existence check above
/// and this write.
#[cfg(unix)]
fn create_env_file(path: &Path, contents: &str) -> std::io::Result<()> {
    use std::io::Write;
    use std::os::unix::fs::OpenOptionsExt;
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(path)?;
    file.write_all(contents.as_bytes())
}

#[cfg(not(unix))]
fn create_env_file(path: &Path, contents: &str) -> std::io::Result<()> {
    std::fs::write(path, contents)
}

/// The GGUF file name the `extract` service will mount: the `CLIO_EXTRACT_GGUF`
/// value in an existing `root/.env`, or the documented default.
///
/// `write_env` never overwrites a user's `.env`, so a name set there has to be
/// read back. A prerequisite check that assumed the default would refuse a
/// stack that the file itself makes correct, and pass one the file breaks.
pub(crate) fn extract_gguf_name(root: &Path) -> String {
    let default = || compose_assets::GGUF_FILE_NAME.to_string();
    let Ok(contents) = std::fs::read_to_string(root.join(".env")) else {
        return default();
    };
    for line in contents.lines() {
        let Some(value) = line.trim().strip_prefix("CLIO_EXTRACT_GGUF=") else {
            continue;
        };
        let value = value.trim().trim_matches(|c| c == '"' || c == '\'');
        if !value.is_empty() {
            return value.to_string();
        }
    }
    default()
}

/// The marker file recording the selection `clio compose up` started, so
/// `clio compose down` tears down the same services without re-asking.
pub(crate) const MARKER_FILE: &str = ".am-compose-services";

/// Record the selection after `up` succeeds.
pub(crate) fn write_marker(root: &Path, selection: &str) -> Result<(), String> {
    std::fs::write(root.join(MARKER_FILE), format!("{selection}\n"))
        .map_err(|e| format!("cannot write {MARKER_FILE}: {e}"))
}

/// Read the recorded selection, if any.
pub(crate) fn read_marker(root: &Path) -> Option<String> {
    std::fs::read_to_string(root.join(MARKER_FILE))
        .ok()
        .map(|text| text.trim().to_string())
        .filter(|text| !text.is_empty())
}

