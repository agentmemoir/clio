//! # Responsibility
//!
//! This module is responsible for the manual's output directory where the platform keeps no descriptor-relative file operations: `--out` is checked component by component, and the per-page target check, temp create, and promote are made through the path.
//!
//! ## Owns
//! - `open`: the component walk that classifies each name, then the directory create
//! - `check_target`, `write_temp`, `remove_temp`, and `promote` through `std::fs`
//!
//! ## Does not own
//! - `OutDir`, the public surface holding this directory (see `cli_manual_write_dir`)
//! - The refusal and failure messages, which the descriptor form shares and which stay in `cli_manual_write_dir`
//!
//! ## Boundary
//!
//! Changes to how a path is checked or written on this platform should normally require changes here; changes to which pages the manual writes should not. Keep this module the path-based form only: no held descriptor and no descriptor-relative call belongs in it.

use super::{
    armed_promote_failure, directory_target, generated, io_error, not_a_directory, page_file_name,
    special_target, symlink_component, symlink_target, temp_exhausted, temp_name, unmarked_target,
};
use crate::cli_error::CliError;
use crate::cli_manual_write::incomplete;
use std::ffi::{OsStr, OsString};
use std::fs;
use std::path::{Path, PathBuf};

/// Resolve `out_dir` through the path: every component must be a real directory, then the directory is created.
pub(super) fn open(out_dir: &Path) -> Result<PathBuf, CliError> {
    let mut walked = PathBuf::new();
    for component in out_dir.components() {
        walked.push(component);
        let meta = match fs::symlink_metadata(&walked) {
            Ok(meta) => meta,
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => continue,
            Err(err) => return Err(io_error("inspect", &walked, &err)),
        };
        if meta.file_type().is_symlink() {
            return Err(symlink_component(&walked));
        }
        if !meta.is_dir() {
            return Err(not_a_directory(&walked));
        }
    }
    fs::create_dir_all(out_dir).map_err(|err| io_error("create", out_dir, &err))?;
    Ok(out_dir.to_path_buf())
}

/// Check one page target through the path: absent, generated by this command, or refused.
pub(super) fn check_target(dir: &Path, file: &str) -> Result<(), CliError> {
    page_file_name(file)?;
    let target = dir.join(file);
    let meta = match fs::symlink_metadata(&target) {
        Ok(meta) => meta,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(err) => return Err(io_error("inspect", &target, &err)),
    };
    if meta.file_type().is_symlink() {
        return Err(symlink_target(&target));
    }
    if meta.is_dir() {
        return Err(directory_target(&target));
    }
    if !meta.file_type().is_file() {
        return Err(special_target(&target));
    }
    let opened = fs::File::open(&target).map_err(|err| io_error("inspect", &target, &err))?;
    if !generated(opened, &target)? {
        return Err(unmarked_target(&target));
    }
    Ok(())
}

/// Write `bytes` to a fresh temp sibling of `file` through the path and return its bare name.
///
/// The path form takes the target's mode from the create alone, because the platform keeps no cheap read of the existing mode; the temp is created create-new, written, and synced. A failure once the temp exists removes it and reports the manual incomplete.
pub(super) fn write_temp(
    dir: &Path,
    shown: &Path,
    file: &str,
    bytes: &[u8],
) -> Result<OsString, CliError> {
    let (tmp, mut staged) = create_temp(dir, shown, file)?;
    let temp_shown = shown.join(&tmp);
    if let Err(err) = write_and_sync(&mut staged, bytes, &temp_shown) {
        remove_temp(dir, &tmp);
        return Err(incomplete(shown, &err));
    }
    Ok(tmp)
}

/// Open a fresh temp sibling of `file` through the path; a leftover name from a crashed run is skipped.
fn create_temp(dir: &Path, shown: &Path, file: &str) -> Result<(OsString, fs::File), CliError> {
    for _ in 0..10 {
        let tmp = temp_name(file);
        let at = dir.join(&tmp);
        match open_new(&at) {
            Ok(staged) => return Ok((tmp, staged)),
            Err(err) if err.kind() == std::io::ErrorKind::AlreadyExists => {}
            Err(err) => return Err(io_error("create", &at, &err)),
        }
    }
    Err(temp_exhausted(&shown.join(file)))
}

/// Remove a temp sibling this module created, best effort, through the path.
pub(super) fn remove_temp(dir: &Path, tmp: &OsStr) {
    let _ = fs::remove_file(dir.join(tmp));
}

/// Rename the temp sibling over its target through the path. A test-only seam can make this one step fail for one exact target.
pub(super) fn promote(dir: &Path, tmp: &OsStr, file: &str) -> Result<(), CliError> {
    let target = dir.join(file);
    if let Some(err) = armed_promote_failure(&target) {
        return Err(err);
    }
    fs::rename(dir.join(tmp), &target).map_err(|err| io_error("promote", &target, &err))
}

/// Create a new temp file at `at`, refusing an existing name.
fn open_new(at: &Path) -> std::io::Result<fs::File> {
    fs::OpenOptions::new().write(true).create_new(true).open(at)
}

/// Write `bytes` to the open temp file and sync it.
fn write_and_sync(temp: &mut fs::File, bytes: &[u8], shown: &Path) -> Result<(), CliError> {
    use std::io::Write;

    temp.write_all(bytes)
        .map_err(|err| io_error("write", shown, &err))?;
    temp.sync_all().map_err(|err| io_error("sync", shown, &err))
}
